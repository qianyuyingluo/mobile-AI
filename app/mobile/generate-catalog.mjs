// Produce the offline phone catalog from the same locked packages as desktop Harness.
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { resolve } from 'node:path'
import { catalogModels, catalogProvider, catalogProviderIds, THINKING_LEVELS } from '../packages/llm/llm-pi-ai/src/catalog.ts'
import { getSupportedThinkingLevels } from '../packages/llm/llm-pi-ai/src/models.ts'
import { DEFAULT_MODELS } from '../packages/llm/llm-deepseek/src/models.ts'
import { modelInfo } from '../packages/llm/llm-deepseek/src/model-info.ts'

const protocols = new Set(['openai-completions', 'openai-responses', 'anthropic-messages', 'google-generative-ai'])
const fields = ['thinking', 'reasoning', 'reasoning_effort', 'output_config', 'enable_thinking',
  'chat_template_kwargs', 'chat_template_args', 'thinking_token_budget', 'thinking_budget_tokens', 'thinking_budget']
const context = { messages: [{ role: 'user', content: 'x', timestamp: 1 }] }

// Stop at the SDK's serialization hook, before transport. This preserves model-specific
// wire values, adaptive thinking and token budgets without shipping Node SDKs to Android.
async function reasoningPayload(provider, model, level) {
  let wire
  const result = await provider.streamSimple(model, context, {
    apiKey: 'offline-catalog', maxRetries: 0,
    reasoning: level === 'off' ? undefined : level,
    onPayload(payload) {
      wire = Object.fromEntries(fields.filter(k => payload[k] !== undefined).map(k => [k, payload[k]]))
      if (payload.thinking && payload.max_tokens) wire.max_tokens = payload.max_tokens
      if (payload.config?.thinkingConfig) wire.generationConfig = { thinkingConfig: payload.config.thinkingConfig }
      throw Error('Offline payload captured')
    },
  }).result()
  if (!wire) throw Error(provider.id + '/' + model.id + ': ' + result.errorMessage)
  return wire
}

export async function generateCatalog() {
  const pool = [], index = new Map()
  function intern(value) {
    const key = JSON.stringify(value)
    if (!index.has(key)) { index.set(key, pool.length); pool.push(value) }
    return index.get(key)
  }
  const groups = []
  for (const id of catalogProviderIds()) {
    const provider = catalogProvider(id)
    const rows = []
    for (const model of catalogModels(id).values()) {
      const levels = model.reasoning ? getSupportedThinkingLevels(model) : []
      const direct = protocols.has(model.api) && /^https:\/\//.test(model.baseUrl) &&
        !model.baseUrl.includes('{') && !['github-copilot', 'azure'].includes(id)
      const wire = {}
      if (direct && model.reasoning) {
        for (const level of ['', ...levels]) wire[level] = await reasoningPayload(provider, model, level || undefined)
      }
      const base = model.baseUrl.replace(/\/+$/, '')
      const suffix = { 'openai-completions': '/chat/completions', 'openai-responses': '/responses',
        'anthropic-messages': '/v1/messages', 'google-generative-ai': '' }[model.api]
      rows.push([model.id, model.name, intern({ api: model.api, endpoint: direct ? base + suffix : '',
        input: model.input, levels, wire, replay: !!model.compat?.requiresReasoningContentOnAssistantMessages })])
    }
    groups.push([id, rows])
  }
  const official = DEFAULT_MODELS.map(m => {
    const info = modelInfo({ models: DEFAULT_MODELS, defaults: {} }, 'deepseek-official', m.id)
    return { id: m.id, name: info.name, input: info.inputModalities, reasoning: info.reasoning }
  })
  const source = '// Generated by app/mobile/generate-catalog.mjs from Harness.\n' +
    'export const levels = ' + JSON.stringify(THINKING_LEVELS) + '\n' +
    'export const official = ' + JSON.stringify(official, null, 2) + '\n' +
    'export const capabilities = [\n' + pool.map(value => '  ' + JSON.stringify(value)).join(',\n') + '\n]\n' +
    'export const groups = [\n' + groups.map(([id, rows]) => '  [' + JSON.stringify(id) + ', [\n' +
      rows.map(row => '    ' + JSON.stringify(row)).join(',\n') + '\n  ]]').join(',\n') + '\n]\n'
  const target = fileURLToPath(new URL('./ui/harness-catalog.js', import.meta.url))
  const previous = await readFile(target, 'utf8').catch(error => {
    if (error.code !== 'ENOENT') throw error
  })
  if (previous !== source) await writeFile(target, source)
}
if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) await generateCatalog()
